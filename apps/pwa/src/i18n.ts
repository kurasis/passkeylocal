export type Language = 'en' | 'ru';
export const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { en, ru };

/** First of the device's preferred languages that the UI supports; English otherwise. */
export function deviceLanguage(languages: readonly string[] = globalThis.navigator?.languages ?? []): Language {
  for (const l of languages) {
    const code = l.toLowerCase().slice(0, 2);
    if (code === 'ru' || code === 'en') return code;
  }
  return 'en';
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Language): Translate {
  const dict = DICTIONARIES[lang];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export const I18nContext = createContext<{ t: Translate; lang: Language }>({ t: translator('en'), lang: 'en' });

export function useT(): Translate {
  return useContext(I18nContext).t;
}

export function useLang(): Language {
  return useContext(I18nContext).lang;
}
